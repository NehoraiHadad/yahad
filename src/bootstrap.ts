import { platformFiles, type PlatformFiles } from './platform-files.js';

export interface FirstOwnerIdentity { format: 1; installationId: string; ownerSid: string; familyId: string; parentUserId: string }
const uuid = /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/;
function firstOwner(value: unknown): FirstOwnerIdentity | undefined {
  if (value === undefined) return undefined;
  const v = value as FirstOwnerIdentity;
  if (!v || v.format !== 1 || !/^[a-f0-9]{32}$/.test(v.installationId) ||
      !/^S-1-5-21-\d+-\d+-\d+-\d+$/.test(v.ownerSid) || !uuid.test(v.familyId) || !uuid.test(v.parentUserId) || v.familyId === v.parentUserId)
    throw new Error('Invalid protected first Owner identity');
  return v;
}

/** Identity is immutable across capability renewal/expiry. It is not an HTTP input. */
export function readFirstOwnerIdentity(path: string | undefined, files: PlatformFiles = platformFiles) {
  if (!path) return undefined;
  const bytes = files.readSetupCapability(path);
  return bytes ? firstOwner(JSON.parse(bytes.toString('utf8')).firstOwner) : undefined;
}

/** Local installer capability. Never generated by the public HTTP server or logged.
 * The installer can renew an expired link; a populated store always closes setup.
 */
export function readBootstrap(path: string | undefined, now = Date.now(), files: PlatformFiles = platformFiles) {
  if (!path) return undefined;
  const bytes = files.readSetupCapability(path);
  if (!bytes) return undefined;
  const data = JSON.parse(bytes.toString('utf8'));
  const identity = firstOwner(data.firstOwner);
  if (typeof data.token !== 'string' || !/^[A-Za-z0-9_-]{43}$/.test(data.token) ||
      !Number.isSafeInteger(data.expiresAt) || data.expiresAt <= now || data.expiresAt > now + 15 * 60_000)
    return undefined;
  return { token: data.token as string, expiresAt: data.expiresAt as number, ...(identity ? { firstOwner: identity } : {}) };
}
