// Input: official https://www.unicode.org/Public/17.0.0/emoji/emoji-test.txt
// No network access: supply a reviewed local copy as argv[2].
import fs from 'node:fs';
import { createHash } from 'node:crypto';
const source = fs.readFileSync(process.argv[2], 'utf8');
if (!source.includes('# Version: 17.0')) throw new Error('Expected Unicode 17.0 data');
const groups = JSON.parse(fs.readFileSync(new URL('../node_modules/unicode-emoji-json/data-by-group.json', import.meta.url)));
const normalize = name => name.toLowerCase().replace(/(?:medium-light|medium-dark|light|medium|dark) skin tone/g, '').replace(/[^a-z0-9]+/g, ' ').trim();
const bases = new Map(groups.flatMap(g => g.emojis.map(e => [normalize(e.name), e.emoji])));
// Unicode uses explicit neutral-person names for the mixed-tone forms of these bases.
bases.set('kiss person person', '💏');
bases.set('couple with heart person person', '💑');
const variants = {}; let total = 0; const unmatched = []; const qualified = new Set();
for (const line of source.split('\n')) {
  const match = line.match(/^([A-F0-9 ]+)\s*; fully-qualified\s*#\s*\S+\s+E[\d.]+\s+(.+)$/);
  if (!match) continue;
  const emoji = String.fromCodePoint(...match[1].trim().split(/\s+/).map(c => parseInt(c, 16)));
  qualified.add(emoji);
  if (!/skin tone/.test(match[2])) continue;
  const base = bases.get(normalize(match[2]));
  if (!base) { unmatched.push(match[2]); continue; }
  (variants[base] ||= []).push(emoji); total++;
}
if (unmatched.length) throw new Error(`Unmapped variants: ${unmatched.join('; ')}`);
const represented = new Set([...groups.flatMap(g => g.emojis.map(e => e.emoji)), ...Object.values(variants).flat()]);
if (qualified.size !== represented.size || [...qualified].some(emoji => !represented.has(emoji))) throw new Error('Catalog does not exactly cover the official fully-qualified set');
const hash = createHash('sha256').update(source).digest('hex');
fs.writeFileSync(new URL('../web/emojiVariants.ts', import.meta.url), `// Generated by scripts/generate-emoji-variants.mjs; do not hand-edit sequences.\n// Copyright © 2025 Unicode, Inc.
// Unicode 17.0 emoji-test.txt SHA-256: ${hash}\n// Source: https://www.unicode.org/Public/17.0.0/emoji/emoji-test.txt\n// License: docs/licenses/UNICODE-LICENSE-V3.txt\nexport const emojiVariants: Record<string, readonly string[]> = ${JSON.stringify(variants)};\n`);
console.log(`${total} official variants across ${Object.keys(variants).length} bases; sha256 ${hash}`);
